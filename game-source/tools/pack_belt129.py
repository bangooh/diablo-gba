#!/usr/bin/env python3
"""Derive last-slot tiles with the existing left edge mirrored at the right.

Only column seven changes. All eleven potion/empty variants retain their art.
The variants use existing free OBJ tiles; no new RAM or OAM entry is needed.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
text = (root / 'generated/belt_tiles.h').read_text()
source = bytes(map(int, re.search(r'belt_tiles\[352\].*?=\{([^}]+)\}', text).group(1).split(',')))
pixels = bytearray(source)
for row in range(len(pixels) // 4):
    at = row * 4
    pixels[at + 3] = (pixels[at + 3] & 15) | ((pixels[at] & 15) << 4)
output = '#pragma once\n/* Generated by tools/pack_belt129.py. */\n'
output += 'static const unsigned char belt_right_tiles[352] __attribute__((aligned(4)))={'
output += ','.join(map(str, pixels)) + '};\n'
(root / 'generated/belt_right_tiles.h').write_text(output)
