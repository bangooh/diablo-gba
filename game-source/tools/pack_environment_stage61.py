#!/usr/bin/env python3
"""Retail Cathedral braziers, wall furniture and native LAMPS/door macros.

Run after pack_door_arches, before pack_prop_atlas. Existing piece/macro indices
never move: old saved architecture and every prior terrain pixel remain valid.
CEL pixels use the existing static BG palette; alpha is never quantized.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
from PIL import Image, ImageDraw
from lz77 import indexed
from make_prop_dirty import damage_table

ROOT = Path(__file__).resolve().parents[1]
BASE_PIECES, BASE_MACROS = 226, 74
SPECS = [('BRAZIER', 'L1Braz', 64, [1,5,9,13,17,21,25]),
         ('SHRINE_L', 'LShrineG', 128, [1,4,7,11]),
         ('SHRINE_R', 'RShrineG', 128, [1,4,7,11]),
         ('BOOKCASE', 'BCase', 96, [1,2,3,4])]

def sha(data): return hashlib.sha256(data).hexdigest()

def array(header, name):
    match = re.search(name + r'\[\](?:\[4\])?=\{(.*?)\};', header, re.S)
    assert match, name
    return [int(x) for x in re.findall(r'\d+', match[1])]

def replace(header, name, values, rows=False):
    value = ','.join(map(str, values)) if not rows else '\n' + ''.join(
        '{' + ','.join(map(str, values[i:i+4])) + '},\n' for i in range(0,len(values),4))
    header, n = re.subn('(' + name + r'\[\](?:\[4\])?=\{).*?(\};)',
                         lambda m: m[1] + value + m[2], header, flags=re.S)
    assert n == 1, name
    return header

def cel(data, frame, width):
    count = struct.unpack_from('<I', data)[0]
    assert 1 <= frame <= count
    lo, hi = struct.unpack_from('<II',data,frame*4)
    raw = data[lo:hi]; pos = struct.unpack_from('<H',raw)[0]
    assert pos == 10
    pixels = bytearray()
    while pos < len(raw):
        n=raw[pos]; pos+=1
        if n>=128: pixels.extend(bytes(256-n))
        else:
            assert n and pos+n<=len(raw)
            pixels.extend(raw[pos:pos+n]); pos+=n
    assert len(pixels)%width == 0
    return Image.frombytes('P',(width,len(pixels)//width),bytes(pixels)).transpose(Image.Transpose.FLIP_TOP_BOTTOM)

def tile_frame(data,word):
    """Retail MIN microtile decoder, shared format with extract_assets.py."""
    im=Image.new('P',(32,32),0)
    if not word:return im
    index=word&4095; kind=(word>>12)&7
    a,b=struct.unpack_from('<II',data,index*4); src=data[a:b]; pos=0
    if kind==0:
        assert len(src)==1024
        return Image.frombytes('P',(32,32),src).transpose(Image.Transpose.FLIP_TOP_BOTTOM)
    if kind==1:
        pixels=bytearray()
        while pos<len(src):
            n=src[pos];pos+=1
            if n>=128:pixels.extend(bytes(256-n))
            else:pixels.extend(src[pos:pos+n]);pos+=n
        assert len(pixels)==1024
        return Image.frombytes('P',(32,32),bytes(pixels)).transpose(Image.Transpose.FLIP_TOP_BOTTOM)
    assert kind in (2,3,4,5)
    widths=list(range(2,33,2))+(list(range(30,0,-2)) if kind in (2,3) else [32]*16)
    for row,w in enumerate(widths):
        pad=(-w)%4;left=kind in (2,4)
        if left:pos+=pad
        line=src[pos:pos+w];pos+=w
        if not left:pos+=pad
        assert len(line)==w
        for x,c in enumerate(line):im.putpixel(((32-w if left else 0)+x,31-row),c)
    assert pos==len(src)
    return im

def piece(cel_data,mini,p):
    im=Image.new('P',(64,160),0)
    for j,word in enumerate(struct.unpack_from('<10H',mini,(p-1)*20)):
        tile=tile_frame(cel_data,word)
        im.paste(tile,((j&1)*32,(j//2)*32),Image.frombytes('L',tile.size,bytes(255 if v else 0 for v in tile.tobytes())))
    return im

def build(root):
    gen=root/'generated';src=root/'source_assets';out={}
    palette=struct.unpack('<256H',(gen/'bg_palette.bin').read_bytes())
    old=struct.unpack('<256H',(src/'bg_stage41/bg_palette.bin').read_bytes())
    mapping=(gen/'background-palette-review/static_index_map.bin').read_bytes()
    static=(gen/'bg_static_slots.bin').read_bytes()
    slots=[i for i in range(1,256) if static[i//8]&(1<<(i%8))]
    rgb=lambda c:(c&31,(c>>5)&31,(c>>10)&31)
    lut=[0]+[mapping[i] or min(slots,key=lambda j:sum((a-b)**2 for a,b in zip(rgb(old[i]),rgb(palette[j])))) for i in range(1,256)]
    assert all(lut[1:]) and not lut[0]
    frames=[];sources=[];lines=['/* Original CEL art; generated by pack_environment_stage61.py. */','#pragma once','#define PROP_ENVIRONMENT_BASE 117']
    for symbol,name,width,selected in SPECS:
        raw=(src/'environment'/f'{name}.CEL').read_bytes();base=117+len(frames)
        lines += [f'#define PROP_{symbol}_BASE {base}',f'#define PROP_{symbol}_FRAMES {len(selected)}']
        for f in selected:
            native=cel(raw,f,width);small=native.resize((width//2,native.height//2),Image.Resampling.NEAREST)
            # L1Braz uses a160px native canvas but only43px of flame. Its
            # lower transparent tail positions that flame atop piece270.
            assert not small.getbbox() or small.getbbox()[1]>=small.height-64
            canvas=Image.new('P',(64,64));canvas.paste(small,((64-small.width)//2,64-small.height))
            before=canvas.tobytes();after=before.translate(bytes(lut))
            assert all(bool(a)==bool(b) for a,b in zip(before,after))
            frames.append(after)
        sources.append({'name':name+'.CEL','source_frames':struct.unpack_from('<I',raw)[0], 'selected_frames_1based':selected,'width':width,'sha256':sha(raw),'virtual_base':base})
    lines += [f'#define PROP_ENVIRONMENT_FRAMES {len(frames)}',f'#define PROP_ENVIRONMENT_FRAME_LAST {116+len(frames)}', '#define PROP_BRAZIER_NATIVE_TICKS 26', '#define PROP_BRAZIER_NATIVE_RADIUS 5','']
    out['environment_props.h']='\n'.join(lines).encode()
    out['environment_props.lz']=indexed(b''.join(frames),4096)
    damage=['/* Exact all-pairs changed 8x8 tiles; includes prop_dirty.h first. */','#pragma once','#include "environment_props.h"']
    damage_table(damage,'brazier_frame_damage','PROP_BRAZIER_FRAMES',frames[:7])
    out['environment_prop_dirty.h']=('\n'.join(damage)+'\n').encode()
    # Append only native LAMPS components; original door25/26 art is already in ROM.
    header=(gen/'dungeon_art.h').read_text()
    ids=array(header,'dart_macro_ids')[:BASE_MACROS]
    macros=array(header,'dart_macros')[:BASE_MACROS*4]
    pieces=array(header,'dart_source_piece')[:BASE_PIECES]
    indices=array(header,'dart_tile_ids')[:BASE_PIECES*40]
    count=json.loads((gen/'door-arches-report.json').read_text())['atlas_bytes_after']
    art=bytearray((gen/'dungeon_art_raw.rle').read_bytes()[:count]);assert len(art)==count
    seen={bytes(art[i:i+64]):i//64 for i in range(0,len(art),64)}
    native_pal=(src/'cathedral/l1_1.pal').read_bytes();colors=[tuple(native_pal[i:i+3]) for i in range(0,768,3)]
    dark=[0]+[min(range(1,256),key=lambda j:sum((colors[j][k]-colors[i][k]*.5)**2 for k in range(3))) for i in range(1,256)]
    terrain_lut=bytes(lut[i] for i in dark)
    til=(src/'cathedral/l1.til').read_bytes();sol=(src/'cathedral/l1.sol').read_bytes()
    cel_data=(src/'butcher/L1.CEL').read_bytes();mini=(src/'butcher/L1.MIN').read_bytes()
    added=[];occludes=array(header,'dart_occludes')[:BASE_PIECES]
    for macro in (25,26,128,129,130):
        native=[v+1 for v in struct.unpack_from('<4H',til,(macro-1)*8)]
        for p in native:
            if p in pieces:continue
            im=piece(cel_data,mini,p);occludes.append(int(bool(im.getbbox() and im.getbbox()[1]<128)))
            raw=im.resize((32,80),Image.Resampling.NEAREST).tobytes().translate(terrain_lut)
            added.append({'piece':p,'variant':len(pieces),'pixels_sha256':sha(raw)})
            pieces.append(p)
            for ty in range(10):
                for tx in range(4):
                    tile=bytes(raw[(ty*8+y)*32+tx*8+x] for y in range(8) for x in range(8))
                    if tile not in seen:seen[tile]=len(art)//64;art.extend(tile)
                    indices.append(seen[tile])
        ids.append(macro);macros.extend(pieces.index(p) for p in native)
    records=[]
    for macro in (25,26,128,129,130):
        records.append([macro]+[v+1 for v in struct.unpack_from('<4H',til,(macro-1)*8)])
    out['environment_props.h']+=('/* Exact L1.TIL native piece IDs, used only during generation. */\nstatic const uint16_t cathedral_environment_macros[][5]={\n'+''.join(' {'+','.join(map(str,r))+'},\n' for r in records)+'};\n').encode()
    assert len(pieces)<256 and len(ids)<125
    header=re.sub(r'DART_COUNT=\d+',f'DART_COUNT={len(pieces)}',header)
    values={'dart_macro_ids':ids,'dart_macros':macros,'dart_source_piece':pieces,
            'dart_solid':[sol[p-1]&1 for p in pieces], 'dart_occludes':occludes,
            'dart_door':array(header,'dart_door')[:BASE_PIECES]+[0]*(len(pieces)-BASE_PIECES),
            'dart_tile_ids':indices, 'dart_tile_flags':[0 if not any(art[i*64:(i+1)*64]) else 1 if all(art[i*64:(i+1)*64]) else 2 for i in indices]}
    for side in (0,1):values[f'dart_door_seam_{side}']=array(header,f'dart_door_seam_{side}')[:BASE_PIECES]+list(range(BASE_PIECES,len(pieces)))
    for name,value in values.items():header=replace(header,name,value,name=='dart_macros')
    out['dungeon_art.h']=header.encode();out['dungeon_art_raw.rle']=bytes(art)
    # Same atlas tile dedup as production, to enforce the total asset budget.
    from pack_prop_atlas import decoded_frames
    existing=[]
    for name in ('prop_frames','door_frames','explosive_barrels','wall_traps'):existing+=decoded_frames(gen/(name+'.lz'))[1]
    def tiles(fs):return {b''.join(f[(ty+y)*64+tx:(ty+y)*64+tx+8] for y in range(8)) for f in fs for ty in range(0,64,8) for tx in range(0,64,8)}
    extra_tiles=len(tiles(frames)-tiles(existing));prop_bytes=extra_tiles*64+len(frames)*128
    terrain_bytes=len(art)-count+(len(pieces)-BASE_PIECES)*(80+40+2+1+1+1+1+1)+len(ids[BASE_MACROS:])*5
    assert prop_bytes+terrain_bytes+7*7*16<=17*1024,(prop_bytes,terrain_bytes)
    rgbpal=[v*255//31 for c in palette for v in rgb(c)]
    sheet=Image.new('RGB',(7*136,3*152),(20,20,23));pen=ImageDraw.Draw(sheet)
    for i,frame in enumerate(frames):
        im=Image.frombytes('P',(64,64),frame);im.putpalette(rgbpal)
        x=(i%7)*136;y=(i//7)*152;sheet.paste(im.convert('RGB').resize((128,128),Image.Resampling.NEAREST),(x,y+20));pen.text((x+3,y+3),str(117+i),fill='white')
    report={'status':'PASS','sources':sources,'environment_frames':len(frames),'additional_prop_tiles':extra_tiles,'additional_prop_rom_bytes':prop_bytes,'additional_terrain_rom_bytes':terrain_bytes,'total_additional_asset_bytes':prop_bytes+terrain_bytes,'additional_damage_metadata_bytes':7*7*16,'persistent_ram_added':0,'macro_ids_appended':ids[BASE_MACROS:],'pieces_appended':added,'prop_pixels_sha256':sha(b''.join(frames)),'palette_policy':'existing static RGB555 slots; nearest only for previously-unused native indices','period':'26 source ticks at20Hz; samples1,5,9,13,17,21,25, last frame2ticks','native_source':'Objects\\L1Braz.CEL, LShrineG.CEL, RShrineG.CEL, BCase.CEL; Levels\\L1Data\\L1.TIL/CEL/MIN/SOL'}
    out['environment-assets-report.json']=(json.dumps(report,indent=2)+'\n').encode()
    return out,report,sheet

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--root',type=Path,default=ROOT);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    outputs,report,sheet=build(args.root)
    for name,data in outputs.items():
        path=args.root/'generated'/name
        if args.check:assert path.read_bytes()==data,name+' stale'
        elif not path.exists() or path.read_bytes()!=data:path.write_bytes(data)
    if not args.check:
        dst=args.root/'generated/stage61-validation/environment';dst.mkdir(parents=True,exist_ok=True);sheet.save(dst/'native-art-contact.png')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
