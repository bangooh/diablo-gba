#!/usr/bin/env python3
"""Pack the original SOL solid/trap flags by native macro and subcell."""
import argparse, hashlib, json, struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 lines=['/* Native TIL/SOL placement metadata. Generated by pack_theme_rules_stage64.py. */','#pragma once']
 sources={}
 for level in range(1,5):
  folder=ROOT/'source_assets/worldgen';tp=folder/f'L{level}.TIL';sp=folder/f'L{level}.SOL'
  til,sol=tp.read_bytes(),sp.read_bytes();values=[85]
  for i in range(len(til)//8):
   flags=0
   for q,piece in enumerate(struct.unpack_from('<4H',til,i*8)):
    v=sol[piece];flags|=((v&1)|((v>>6)&2))<<(q*2)
   values.append(flags)
  lines.append(f'static const uint8_t theme_macro_flags_{level}[]={{'+','.join(map(str,values))+'};')
  sources[str(tp.relative_to(ROOT))]=hashlib.sha256(til).hexdigest();sources[str(sp.relative_to(ROOT))]=hashlib.sha256(sol).hexdigest()
 data=('\n'.join(lines)+'\n').encode();out=ROOT/'generated/theme_rules.h'
 if a.check:assert out.read_bytes()==data,'theme_rules.h is stale'
 else:out.write_bytes(data)
 print(json.dumps({'status':'PASS','bytes':len(data),'sha256':hashlib.sha256(data).hexdigest(),'source_sha256':sources},indent=2))
if __name__=='__main__':main()
