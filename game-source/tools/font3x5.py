"""Hand-hinted 3x5 uppercase HUD font; four-pixel horizontal advance."""
PATTERNS = {
' ':'000 000 000 000 000', ':':'000 010 000 010 000',
'0':'111 101 101 101 111','1':'010 110 010 010 111',
'2':'110 001 010 100 111','3':'110 001 010 001 110',
'4':'101 101 111 001 001','5':'111 100 110 001 110',
'6':'011 100 111 101 111','7':'111 001 010 010 010',
'8':'111 101 111 101 111','9':'111 101 111 001 110',
'A':'010 101 111 101 101','B':'110 101 110 101 110',
'C':'011 100 100 100 011','D':'110 101 101 101 110',
'E':'111 100 110 100 111','F':'111 100 110 100 100',
'G':'011 100 101 101 011','H':'101 101 111 101 101',
'I':'111 010 010 010 111','J':'001 001 001 101 010',
'K':'101 101 110 101 101','L':'100 100 100 100 111',
'M':'101 111 111 101 101','N':'101 111 111 111 101',
'O':'010 101 101 101 010','P':'110 101 110 100 100',
'Q':'010 101 101 111 011','R':'110 101 110 101 101',
'S':'011 100 010 001 110','T':'111 010 010 010 010',
'U':'101 101 101 101 111','V':'101 101 101 101 010',
'W':'101 101 111 111 101','X':'101 101 010 101 101',
'Y':'101 101 010 010 010','Z':'111 001 010 100 111',
}
GLYPHS=''.join(sorted(PATTERNS))
ROWS={c:[int(s,2) for s in PATTERNS[c].split()] for c in GLYPHS}
def render(text,tiles,fg,bg):
    ink={(1+i*4+x,1+y) for i,c in enumerate(text) for y,row in enumerate(ROWS[c]) for x in range(3) if row & (4>>x)}
    outline={(x+dx,y+dy) for x,y in ink for dx,dy in ((-1,0),(1,0),(0,-1),(0,1))}
    return bytes(fg if (t*8+x,y) in ink else bg if (t*8+x,y) in outline else 0 for t in range(tiles) for y in range(8) for x in range(8))
