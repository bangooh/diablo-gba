#!/usr/bin/env python3
"""Preserve complete native Sorcerer/common ending audio as mono IMA4.

python3 tools/pack_ending_audio.py [--rate 8192|16384] [--check]
Source SMKs are retained under source_assets/ending. Payloads use the asset
bundle's .lz suffix but are raw low-nibble-first IMA4, not LZ streams. Every
PCM16 input sample has one nibble; predictor/index start at zero for each clip.
"""
from array import array
from pathlib import Path
import argparse
import hashlib
import json
import math
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
STEP = (7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,50,
        55,60,66,73,80,88,97,107,118,130,143,157,173,190,209,230,253,
        279,307,337,371,408,449,494,544,598,658,724,796,876,963,1060,
        1166,1282,1411,1552,1707,1878,2066,2272,2499,2749,3024,3327,
        3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,10442,
        11487,12635,13899,15289,16818,18500,20350,22385,24623,27086,
        29794,32767)
INDEX = (-1,-1,-1,-1,2,4,6,8)
SOURCES = (
    ('sorcerer','DiabVic1','1db2a2bf4994633ac04ce843d29ebdabe5cf937f8f68e810a4695444aa10cd29'),
    ('common','Diabend','ce6e5a04e4f557362033c3fe07b1a54b5029f875fee652ab9adcc8f3153efa75'),
)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def encode(samples):
    predictor = index = 0
    packed = bytearray((len(samples)+1)//2)
    decoded = array('h')
    for n, sample in enumerate(samples):
        diff = sample-predictor
        code = 8 if diff < 0 else 0
        diff = abs(diff)
        step = STEP[index]
        change = step >> 3
        for bit, value in ((4,step),(2,step >> 1),(1,step >> 2)):
            if diff >= value:
                code |= bit
                diff -= value
                change += value
        predictor += -change if code & 8 else change
        predictor = max(-32768,min(32767,predictor))
        index = max(0,min(88,index+INDEX[code & 7]))
        packed[n//2] |= code << ((n & 1)*4)
        decoded.append(predictor)
    return bytes(packed), decoded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rate',type=int,choices=(8192,16384),default=8192)
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    repeat = 16384//args.rate
    header = ['/* Generated by tools/pack_ending_audio.py. Raw IMA4 payloads. */',
              '#pragma once','#include <stdint.h>',
              f'#define ENDING_AUDIO_RATE {args.rate}',
              '#define ENDING_AUDIO_OUTPUT_RATE 16384',
              f'#define ENDING_AUDIO_REPEAT {repeat}']
    metadata = {'codec':'IMA4, initial predictor/index0, one nibble per PCM16 sample, low nibble first',
                'source_rate':22050,'encoded_rate':args.rate,'output_rate':16384,
                'output_repeat':repeat,'trimmed_samples':0,'clips':[]}
    for label, name, expected in SOURCES:
        source = ROOT/'source_assets/ending'/(name+'.smk')
        assert sha(source.read_bytes()) == expected, source
        probe = json.loads(subprocess.check_output(['ffprobe','-v','error','-show_streams','-show_format','-of','json',str(source)]))
        native = subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-map','0:a:0','-vn','-ac','1','-ar','22050','-f','s16le','-'])
        raw = subprocess.check_output(['ffmpeg','-v','error','-f','s16le','-ar','22050','-ac','1','-i','pipe:0','-ar',str(args.rate),'-f','s16le','-'],input=native)
        samples = array('h',raw)
        if sys.byteorder != 'little':
            samples.byteswap()
        packed, decoded = encode(samples)
        out = ROOT/'generated'/('audio_ending_'+label+'.lz')
        if args.check:
            assert out.read_bytes() == packed, out
        else:
            out.write_bytes(packed)
        tag = 'ENDING_AUDIO_'+label.upper()
        header += [f'extern const uint8_t asset_audio_ending_{label}[];',
                   f'#define {tag}_SAMPLES {len(samples)}',
                   f'#define {tag}_OUTPUT_SAMPLES {len(samples)*repeat}',
                   f'#define {tag}_BYTES {len(packed)}']
        square = sum(int(v)*int(v) for v in samples)
        error = sum((int(a)-int(b))**2 for a,b in zip(samples,decoded))
        pcm8 = bytes((v >> 8) & 255 for v in decoded)
        metadata['clips'].append({'name':label,'source':str(source.relative_to(ROOT)),
            'source_sha256':expected,'video_seconds':float(probe['format']['duration']),
            'native_audio_samples':len(native)//2,'native_audio_seconds':len(native)/44100,
            'input_samples':len(samples),'output_samples':len(samples)*repeat,
            'playback_seconds':len(samples)/args.rate,'encoded_bytes':len(packed),
            'encoded_sha256':sha(packed),'decoded_pcm8_sha256':sha(pcm8),
            'adpcm_snr_db':round(10*math.log10(square/error),2),
            'source_peak':max(abs(v) for v in samples),
            'decoded_peak':max(abs(v) for v in decoded)})
    header = '\n'.join(header)+'\n'
    metadata['aligned_rom_bytes'] = sum((c['encoded_bytes']+3)&~3 for c in metadata['clips'])
    if args.check:
        assert (ROOT/'generated/ending_audio.h').read_text() == header
    else:
        (ROOT/'generated/ending_audio.h').write_text(header)
        (ROOT/'generated/ending-audio-report.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(json.dumps(metadata,indent=2))


if __name__ == '__main__':
    main()
