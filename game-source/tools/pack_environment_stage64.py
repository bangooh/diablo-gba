#!/usr/bin/env python3
"""Retail fountain/theme CELs at half resolution and complete LS_FOUNTAIN PCM.

The three ten-frame fountains sample every other native frame at five FPS;
Tears uses the four frames named by objdat.cpp, not the spare CEL frames.
Skeleton fire, banners, bodies, burning crosses, goat shrines and cauldrons
complete the themed objects; existing candles, books and racks are reused.
Every selected pixel follows the established static background palette map.
Run before pack_prop_atlas.py. Optional --mpq refreshes native source files.
"""
from pathlib import Path
import argparse, hashlib, json, re, struct, subprocess, wave
from PIL import Image, ImageDraw
from audio_pcm import guarded_pcm
from lz77 import indexed
from make_prop_dirty import damage_table
from pack_environment_stage61 import cel

ROOT=Path(__file__).resolve().parents[1]
SPECS=[('BLOOD_FOUNTAIN','BloodFnt',96,[1,3,5,7,9],10),
       ('PURIFYING_FOUNTAIN','PFountn',128,[1,3,5,7,9],10),
       ('MURKY_FOUNTAIN','MFountn',128,[1,3,5,7,9],10),
       ('TEAR_FOUNTAIN','TFountn',128,[1,2,3,4],8),
       ('SKEL_FIRE','SkulFire',96,[1,3,5,7,9,11],11),
       ('THEME_BANNER','Banner',96,[1,2,3],3),
       ('THEME_DECAP','Decap',96,list(range(1,9)),8),
       ('BURNING_CROSS','BurnCros',160,[1,3,5,7,9],10),
       ('GOAT_SHRINE','GoatShrn',96,[1,3,5,7,9],10),
       ('CAULDRON','Cauldren',96,[1,3],3)]
def sha(data):return hashlib.sha256(data).hexdigest()

def build():
    src=ROOT/'source_assets/environment_stage64';gen=ROOT/'generated'
    palette=struct.unpack('<256H',(gen/'bg_palette.bin').read_bytes())
    old=struct.unpack('<256H',(ROOT/'source_assets/bg_stage41/bg_palette.bin').read_bytes())
    mapping=(gen/'background-palette-review/static_index_map.bin').read_bytes()
    static=(gen/'bg_static_slots.bin').read_bytes()
    slots=[i for i in range(1,256) if static[i//8]&(1<<(i%8))]
    rgb=lambda c:(c&31,(c>>5)&31,(c>>10)&31)
    lut=bytes([0]+[mapping[i] or min(slots,key=lambda j:sum((a-b)**2 for a,b in zip(rgb(old[i]),rgb(palette[j])))) for i in range(1,256)])
    assert lut[0]==0 and all(lut[1:])
    base=int(re.search(r'#define PROP_ENVIRONMENT_FRAME_LAST (\d+)',(gen/'environment_props.h').read_text())[1])+1
    lines=['/* Original CEL pixels; generated by pack_environment_stage64.py. */','#pragma once',f'#define PROP_FOUNTAIN_BASE {base}']
    dirty=['/* Exact all-pairs color/opacity changes. prop_dirty.h included first. */','#pragma once','#include "fountain_props.h"']
    frames=[];sources=[]
    for symbol,name,width,selected,expected in SPECS:
        raw=(src/(name+'.CEL')).read_bytes();count=struct.unpack_from('<I',raw)[0];assert count==expected
        lines += [f'#define PROP_{symbol}_BASE {base+len(frames)}',f'#define PROP_{symbol}_FRAMES {len(selected)}']
        group=[]
        for f in selected:
            native=cel(raw,f,width);small=native.resize((width//2,native.height//2),Image.Resampling.NEAREST)
            if name=='BurnCros':
                # Remove transparent margins only. Runtime (+8,-8) puts
                # the retained half-resolution pixels at native coordinates.
                box=small.getbbox();assert box[0]>=16 and box[1]>=8 and box[2]<=80 and box[3]<=72
                small=small.crop((16,8,80,72))
            assert small.width<=64 and small.height<=64
            canvas=Image.new('P',(64,64));canvas.paste(small,((64-small.width)//2,64-small.height))
            before=canvas.tobytes();after=before.translate(lut)
            assert all(bool(a)==bool(b) for a,b in zip(before,after))
            group.append(after)
        if name not in ('Banner','Decap','Cauldren'):
            damage_table(dirty,symbol.lower()+'_frame_damage',f'PROP_{symbol}_FRAMES',group)
        frames.extend(group)
        sources.append({'name':name+'.CEL','native_dimensions':[width,native.height],'native_frames':count,
                        'selected_frames_1based':selected,'native_delay_ticks':0 if name in ('Banner','Decap','Cauldren','BurnCros') else 2,
                        'runtime_delay_ticks':0 if name in ('Banner','Decap','Cauldren') else 2 if name=='TFountn' else 4,
                        'runtime_offset':[8,-8] if name=='BurnCros' else [0,0],
                        'sha256':sha(raw),'decoded_sha256':sha(b''.join(group))})
    lines += [f'#define PROP_FOUNTAIN_FRAMES {len(frames)}',f'#define PROP_FOUNTAIN_FRAME_LAST {base+len(frames)-1}','']
    raw=(src/'Fountain.wav').read_bytes()
    with wave.open(str(src/'Fountain.wav'),'rb') as w:rate=w.getframerate();samples=w.getnframes();assert (w.getnchannels(),w.getsampwidth(),rate)==(1,1,22050)
    command=['ffmpeg','-v','error','-i',str(src/'Fountain.wav'),'-ac','1','-ar','16384','-af','volume=0.85','-f','s8','-']
    pcm=subprocess.check_output(command);assert pcm==subprocess.check_output(command)
    assert abs(len(pcm)-samples*16384/rate)<=1
    guarded=guarded_pcm(pcm);guarded+=bytes((-len(guarded))%16)
    assert len(guarded)-len(pcm)>=1024 and not any(guarded[len(pcm):])
    report={'source_revision':'9f01757243412bb154d02d9af65c804159e6e0ea','sources':sources,
            'frame_base':base,'frame_count':len(frames),'decoded_sha256':sha(b''.join(frames)),
            'persistent_ram_added':0,'audio':{'source':'Sfx\\Misc\\Fountain.wav','sha256':sha(raw),'native_rate':rate,'native_samples':samples,
            'native_seconds':samples/rate,'rate':16384,'samples':len(pcm),'seconds':len(pcm)/16384,'volume':0.85,
            'guarded_bytes':len(guarded),'pcm_sha256':sha(pcm),'guarded_sha256':sha(guarded),'full_source_duration_retained':True}}
    output={'fountain_props.h':'\n'.join(lines).encode(),'fountain_props.lz':indexed(b''.join(frames),4096),
            'fountain_prop_dirty.h':('\n'.join(dirty)+'\n').encode(),'audio_fountain.lz':guarded,
            'fountain_audio.h':('#pragma once\n#include <stdint.h>\nextern const uint8_t asset_audio_fountain[];\n#define AUDIO_FOUNTAIN_LENGTH '+str(len(pcm))+'\n').encode(),
            'environment-stage64-report.json':(json.dumps(report,indent=2)+'\n').encode()}
    return output,report,frames,palette

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--mpq',type=Path);a=p.parse_args()
    if a.mpq:
        assert not a.check
        import mpyq
        from extract_assets import read_mpq
        archive=mpyq.MPQArchive(str(a.mpq),listfile=False);src=ROOT/'source_assets/environment_stage64';src.mkdir(exist_ok=True)
        for _,name,_,_,_ in SPECS:(src/(name+'.CEL')).write_bytes(read_mpq(archive,'Objects\\'+name+'.CEL'))
        (src/'Fountain.wav').write_bytes(read_mpq(archive,'Sfx\\Misc\\Fountain.wav'))
    output,report,frames,palette=build()
    for name,data in output.items():
        path=ROOT/'generated'/name
        if a.check:assert path.read_bytes()==data,name+' is stale'
        elif not path.exists() or path.read_bytes()!=data:path.write_bytes(data)
    print(json.dumps({'status':'PASS','frames':len(frames),'audio_bytes':report['audio']['guarded_bytes'],'source_frames_and_alpha_verified':True}))
if __name__=='__main__':main()
