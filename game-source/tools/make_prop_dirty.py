#!/usr/bin/env python3
"""Exact tile damage for native candle and barrel animation transitions."""
from pathlib import Path
import argparse
import hashlib
import re
import struct
from lz77 import decompress


def damage_table(lines, name, size, frames):
    """All pairs handle draws that skip simulation animation frames."""
    lines.append(f'static const PropFrameDamage {name}[{size}][{size}]={{')
    for before in frames:
        lines.append(' {')
        for after in frames:
            color = opacity = 0
            for p, (a, b) in enumerate(zip(before, after)):
                bit = 1 << ((p // 64 // 8) * 8 + (p % 64 // 8))
                if a != b:
                    color |= bit
                if bool(a) != bool(b):
                    opacity |= bit
            words = lambda value: f'0x{value & 0xffffffff:08x}u,0x{value >> 32:08x}u'
            lines.append('  {{' + words(color) + '},{' + words(opacity) + '}},')
        lines.append(' },')
    lines.append('};')


def generate(root):
    definitions = (root / 'generated/water_candles.h').read_text()
    base = int(re.search(r'#define PROP_WATER_CANDLE_BASE (\d+)', definitions)[1])
    count = int(re.search(r'#define PROP_WATER_CANDLE_FRAMES (\d+)', definitions)[1])
    blob = (root / 'generated/prop_frames.bin').read_bytes()
    frames = [blob[(base + i) * 4096:(base + i + 1) * 4096] for i in range(count)]
    assert all(len(frame) == 4096 for frame in frames)
    definitions = (root / 'generated/prop_frames.h').read_text()
    barrel_base = int(re.search(r'#define PROP_BARREL_BASE (\d+)', definitions)[1])
    barrel_count = int(re.search(r'#define PROP_BARREL_FRAMES (\d+)', definitions)[1])
    barrel_frames = [blob[(barrel_base+i)*4096:(barrel_base+i+1)*4096] for i in range(barrel_count)]
    explosive = (root / 'generated/explosive_barrels.lz').read_bytes()
    explosive_count = struct.unpack_from('<I', explosive)[0]
    offsets = struct.unpack_from('<'+'I'*(explosive_count+1), explosive, 4)
    explosive_frames = [decompress(explosive[lo:hi]) for lo, hi in zip(offsets, offsets[1:])]
    expected_count = int(re.search(r'#define PROP_BARRELEX_FRAMES (\d+)', (root/'generated/explosive_barrels.h').read_text())[1])
    assert explosive_count == expected_count
    assert all(len(frame) == 4096 for frame in barrel_frames+explosive_frames)
    lines = [
        '/* Generated by tools/make_prop_dirty.py; do not edit. */',
        '#ifndef PROP_DIRTY_H', '#define PROP_DIRTY_H', '#include <stdint.h>',
        '#include "water_candles.h"', '#include "prop_frames.h"', '#include "explosive_barrels.h"',
        '/* Native candle pixels SHA-256: ' + hashlib.sha256(b''.join(frames)).hexdigest() + ' */',
        '/* Native barrel pixels SHA-256: ' + hashlib.sha256(b''.join(barrel_frames)).hexdigest() + ' */',
        '/* Native explosive pixels SHA-256: ' + hashlib.sha256(b''.join(explosive_frames)).hexdigest() + ' */',
        'typedef struct { uint32_t color[2],opacity[2]; } PropFrameDamage;',
    ]
    damage_table(lines, 'candle_frame_damage', 'PROP_WATER_CANDLE_FRAMES', frames)
    damage_table(lines, 'barrel_frame_damage', 'PROP_BARREL_FRAMES', barrel_frames)
    damage_table(lines, 'explosive_barrel_frame_damage', 'PROP_BARRELEX_FRAMES', explosive_frames)
    lines += ['#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / 'generated/prop_dirty.h'
    content = generate(root)
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('Stale prop damage metadata; run python3 tools/make_prop_dirty.py')
        print('PASS: candle/barrel damage metadata matches all native frame pairs')
    else:
        target.write_text(content)
        print('Generated exact color/opacity damage for all candle/barrel frame pairs')
