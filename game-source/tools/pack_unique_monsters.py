"""Fit native unique translations to the unchanged Stage20 shared actor images.

Retail first applies the base monster translation to the CL2, then applies the
unique translation at draw time. These two tables are composed in that order.
Hardware palette entries are fit against the actual current image indices;
there is no runtime pixel remap and no copied animation or shared-pool change.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import struct
import tempfile

import numpy as np
from PIL import Image

from extract_assets import cl2_frames
from pack_gba_assets import tile_bytes
from pack_hot_monsters import Decoder
from lz77 import compress, decompress

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'generated'
SOURCE = ROOT / 'source_assets/monster_catalog'
TRANSLATIONS = SOURCE / 'unique_translations'
GROUPS = (
    (50, 9, 'bonehead', 'Bonehead Keenaxe', 'BHKA'),
    (51, 7, 'rotcarnage', 'Rotcarnage', 'RCRN'),
    (52, 24, 'breakspine', 'Breakspine', 'GENERAL'),
    (53, 26, 'blackstorm', 'Blackstorm', 'GENERAL'),
)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def translation(base, unique):
    """InitMonsterTRN changes 255 to zero before applying the base table."""
    assert len(base) == len(unique) == 256
    return bytes(unique[0 if base[pixel] == 255 else base[pixel]]
                 for pixel in range(256))


def rgb555(words):
    return np.stack([(words >> shift) & 31 for shift in (0, 5, 10)], axis=-1)


def fit(counts, target):
    result = np.zeros((16, 3), np.int64)
    for index in range(1, 16):
        total = int(counts[index].sum())
        if total:
            result[index] = np.floor(counts[index] @ target / total + .5).astype(np.int64)
    return (result[:, 0] | result[:, 1] << 5 | result[:, 2] << 10).astype('<u2')


def error(counts, fitted, target):
    weights = counts.copy()
    weights[0] = 0
    delta = rgb555(fitted).astype(np.int64)[:, None, :] - target[None, :, :]
    total = int(weights.sum())
    mse = float((weights * (delta * delta).sum(axis=2)).sum()) / (3 * max(total, 1))
    return {'opaque_pixels': total, 'rgb8_channel_rmse': mse ** .5 * 255 / 31}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mpq', type=Path, nargs='?')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    archive = None
    if not args.check:
        if not args.mpq:
            parser.error('DIABDAT.MPQ is required unless --check is used')
        import mpyq
        from extract_assets import read_mpq
        archive = mpyq.MPQArchive(str(args.mpq), listfile=False)
        TRANSLATIONS.mkdir(exist_ok=True)
        for name in sorted({row[4] for row in GROUPS}):
            raw = read_mpq(archive, 'Monsters\\Monsters\\' + name + '.TRN')
            assert len(raw) == 256
            (TRANSLATIONS / (name + '.TRN')).write_bytes(raw)

    records = json.loads((SOURCE / 'monsters.json').read_text())['monsters']
    assert len(records) == 50, 'ordinary source catalog must retain its 50-kind identity'
    unique_records = {row['kind']: row for row in json.loads((SOURCE / 'uniques.json').read_text())['monsters']}
    native_palette = (ROOT / 'source_assets/worldgen/L1_1.PAL').read_bytes()
    colors = np.frombuffer(native_palette, np.uint8).reshape(256, 3).astype(np.int64)
    bright = np.array([[round(c + (255 - c) * .18) >> 3 for c in color]
                       for color in colors], np.int64)
    normal = colors >> 3
    existing_art = (OUT / 'cathedral_monster_art.inc').read_text().splitlines()
    existing_hit = (OUT / 'cathedral_monster_hit.inc').read_text().splitlines()
    header = ['/* Generated by tools/pack_unique_monsters.py. */', '#pragma once', '#include <stdint.h>']
    arts, hits, rows = [], [], []
    dependencies = {}
    with tempfile.TemporaryDirectory(prefix='unique-palette-') as temp:
        decoder = Decoder(temp, (OUT / 'hero_frame_pool.lz').read_bytes())
        for kind, base_kind, key, name, trn in GROUPS:
            base = records[base_kind]
            folder = SOURCE / base['key']
            base_trn = (folder / 'translation.trn').read_bytes()
            unique_trn = (TRANSLATIONS / (trn + '.TRN')).read_bytes()
            native_path = 'Monsters\\Monsters\\' + trn + '.TRN'
            assert unique_records[kind]['base_kind'] == unique_records[kind + 4]['base_kind'] == base_kind
            assert unique_records[kind]['translation_chain'] == [base['translation'], native_path]
            if archive is not None:
                assert read_mpq(archive, base['translation']) == base_trn
            composed = translation(base_trn, unique_trn)
            counts = np.zeros((16, 256), np.int64)
            clips = []
            source_hashes = {}
            for state in ('nwahs' if base_kind in (24, 26) else 'nwah'):
                asset = 'ai_rhino_s' if state == 's' else base['key'] + '_' + state
                clip = (OUT / (asset + '.lz')).read_bytes()
                path = folder / (state + '.cl2')
                # The imported charge clip shares the Horned Demon's raw CL2.
                if state == 's':
                    path = SOURCE / 'horned_demon/s.cl2'
                raw = path.read_bytes()
                source_hashes[str(path.relative_to(ROOT))] = sha(raw)
                groups = cl2_frames(raw, base['width'])
                count = len(groups[0])
                assert len(groups) == 8 and all(len(group) == count for group in groups)
                decoded = decoder.frames(clip, count * 8)
                for frame, native in zip(decoded, (im for group in groups for im in group)):
                    side = max(128, base['width'], native.height)
                    canvas = Image.new('P', (side, side))
                    canvas.paste(native, ((side - native.width) // 2, side - native.height))
                    native_indices = np.frombuffer(tile_bytes(canvas.resize(
                        (64, 64), Image.Resampling.NEAREST), 8), np.uint8)
                    packed = np.frombuffer(frame, np.uint8)
                    indices = np.empty(4096, np.uint8)
                    indices[0::2], indices[1::2] = packed & 15, packed >> 4
                    assert np.array_equal(indices > 0, native_indices > 0), (key, state, 'geometry changed')
                    counts += np.bincount(indices.astype(np.int64) * 256 + native_indices,
                                          minlength=16 * 256).reshape(16, 256)
                dependencies[asset + '.lz'] = sha(clip)
                clips.append({'asset': asset, 'frames': len(decoded), 'decoded_sha256': sha(b''.join(decoded))})
            mapping = np.frombuffer(composed, np.uint8)
            fitted_normal, fitted_bright = fit(counts, normal[mapping]), fit(counts, bright[mapping])
            palette = np.concatenate((fitted_normal, fitted_bright)).astype('<u2').tobytes()
            assert fitted_normal[0] == fitted_bright[0] == 0
            assert np.all(rgb555(fitted_bright)[1:] >= rgb555(fitted_normal)[1:])
            metrics = error(counts, fitted_normal, normal[mapping])
            assert metrics['rgb8_channel_rmse'] < 24, (key, metrics)
            blob = compress(palette)
            assert decompress(blob) == palette
            target = OUT / ('unique_' + key + '_palette.lz')
            if args.check:
                assert target.read_bytes() == blob
            else:
                target.write_bytes(blob)
            header.append('extern const uint8_t asset_unique_' + key + '_palette[];')
            line = existing_art[base_kind - 7]
            line = line.replace('asset_' + base['key'] + '_palette', 'asset_unique_' + key + '_palette')
            line = re.sub(r',\d+,\d+,"[^"]+"\},$', ',8,12,"' + name.upper() + '"},', line)
            arts.append(line)
            hits.append(existing_hit[base_kind - 7])
            used = counts[1:].sum(axis=0) > 0
            rows.append({
                'kind': kind, 'member_kind': kind + 4, 'key': key, 'base_kind': base_kind,
                'base_key': base['key'], 'name': name, 'unique_translation': trn,
                'base_translation_sha256': sha(base_trn), 'unique_translation_sha256': sha(unique_trn),
                'composed_translation_sha256': sha(composed), 'sources': source_hashes,
                'clips': clips, 'normal_palette_rgb555': fitted_normal.tolist(),
                'selected_palette_rgb555': fitted_bright.tolist(), 'normal_error': metrics,
                'composed_black_source_colors': int(np.count_nonzero(used & (mapping == 0))),
                'black_pixels_keep_opacity': True, 'bytes': len(blob), 'sha256': sha(blob),
                'bank': 8, 'selected_bank': 12,
            })
    for _, base_kind, *_ in GROUPS:
        arts.append(existing_art[base_kind - 7])
        hits.append(existing_hit[base_kind - 7])
    report = {
        'source_revision': '9f01757243412bb154d02d9af65c804159e6e0ea',
        'translation_order': 'unique[base[raw CL2 pixel]]; base 255 is normalized to zero',
        'native_palette_sha256': sha(native_palette), 'leaders': rows,
        'additional_palette_bytes': sum(row['bytes'] for row in rows),
        'additional_palette_aligned_bytes': sum((row['bytes'] + 3) & ~3 for row in rows),
        'image_dependencies': dependencies, 'animation_bytes_added': 0,
        'runtime_pixel_remaps_added': 0, 'existing_image_indices_changed': False,
    }
    outputs = {
        'unique_monsters.h': '\n'.join(header) + '\n',
        'unique_monster_art.inc': '\n'.join(arts) + '\n',
        'unique_monster_hit.inc': '\n'.join(hits) + '\n',
        'unique-monsters-art-report.json': json.dumps(report, indent=2) + '\n',
    }
    for name, content in outputs.items():
        if args.check:
            assert (OUT / name).read_text() == content, name
        else:
            (OUT / name).write_text(content)
    print('PASS four native unique palettes, eight actor/hit aliases;',
          report['additional_palette_bytes'], 'additional bytes; existing animation pixels unchanged')


if __name__ == '__main__':
    main()
