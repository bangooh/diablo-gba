"""Build ten-step PCM gain LUTs; no gain arithmetic in the audio IRQ."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Music5 is 0.78 native PCM: Stage46 default0.65 multiplied by1.20.
# Upper music levels use remaining PCM headroom without sample clipping.
MUSIC_PERMILLE = [156, 312, 468, 624, 780, 824, 868, 912, 956, 1000]
EFFECTS_PERMILLE = list(range(200, 2001, 200))


def scale(sample, gain):
    value = (abs(sample) * gain + 500) // 1000
    return max(-128, min(127, -value if sample < 0 else value))


def render():
    output = ('/* Generated by tools/pack_audio_gains.py. Signed PCM, nearest rounding.\n'
              ' * Music1..10:15.6,31.2,46.8,62.4,78,82.4,86.8,91.2,95.6,100%.\n'
              ' * Sound1..10:20..200%; clip after summing voices. */\n'
              '#pragma once\n#include <stdint.h>\n')
    for name, gains, samples in [('music_gain', MUSIC_PERMILLE,
                                  [i if i < 128 else i - 256 for i in range(256)]),
                                 ('effects_gain', EFFECTS_PERMILLE, list(range(-256, 256)))]:
        output += f'static const int8_t {name}[10][{len(samples)}]={{\n'
        for gain in gains:
            output += ' {' + ','.join(str(scale(s, gain)) for s in samples) + '},\n'
        output += '};\n'
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'generated/audio_gains.h'
    expected = render()
    if args.check:
        assert path.read_text() == expected, 'generated/audio_gains.h is stale'
    else:
        path.write_text(expected)
    assert MUSIC_PERMILLE[4] == 650 * 120 // 100
    assert EFFECTS_PERMILLE[4] == 1000
    assert all(scale(s, 1000) == s for s in range(-128, 128))
    print('PASS: music default5 = Stage46 +20%; sound default5 = native; '
          'ten monotonic levels with signed saturation')


if __name__ == '__main__':
    main()
