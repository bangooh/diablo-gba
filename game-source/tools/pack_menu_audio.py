#!/usr/bin/env python3
"""Encode only the title/main-menu music as complete looping 8192 Hz IMA4.

Town and dungeon music assets are unchanged. The existing0.60 source gain is
retained; the Music option still applies its normal gain during playback.
"""
from array import array
from pathlib import Path
import argparse
import hashlib
import json
import math
import subprocess
import sys
import wave

from pack_ending_audio import encode

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'source_assets/combat/music_menu.wav'
SOURCE_SHA = 'f53afe310d0b68df7e9d0a0e2879d28fe44aa69e98d2462294a6fb130d9ed93a'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assert sha(SOURCE.read_bytes()) == SOURCE_SHA
    with wave.open(str(SOURCE)) as native:
        native_samples, native_rate = native.getnframes(), native.getframerate()
    raw = subprocess.check_output([
        'ffmpeg', '-v', 'error', '-i', str(SOURCE), '-ac', '1', '-ar', '8192',
        '-af', 'volume=0.60', '-f', 's16le', '-'])
    samples = array('h', raw)
    if sys.byteorder != 'little':
        samples.byteswap()
    packed, decoded = encode(samples)
    pcm8 = bytes((value >> 8) & 255 for value in decoded)
    signal = sum(int(value) ** 2 for value in samples)
    error = sum((int(a) - int(b)) ** 2 for a, b in zip(samples, decoded))
    legacy = (ROOT / 'generated/audio_music_menu.lz').read_bytes()
    metadata = {
        'source': str(SOURCE.relative_to(ROOT)), 'source_sha256': SOURCE_SHA,
        'scope': 'Title/main-menu track2 only; town0 and dungeon1 unchanged',
        'codec': 'Continuous IMA4, initial predictor/index0, low nibble first; decoder resets at each loop',
        'native_rate': native_rate, 'native_samples': native_samples,
        'native_seconds': native_samples / native_rate,
        'source_gain': 0.60, 'encoded_rate': 8192,
        'input_samples': len(samples), 'output_repeat': 2,
        'output_rate': 16384, 'output_samples': len(samples) * 2,
        'playback_seconds': len(samples) / 8192,
        'encoded_bytes': len(packed), 'aligned_rom_bytes': (len(packed) + 3) & ~3,
        'encoded_sha256': sha(packed), 'decoded_pcm8_sha256': sha(pcm8),
        'previous_asset_bytes': len(legacy), 'previous_asset_sha256': sha(legacy),
        'raw_aligned_bytes_saved': ((len(legacy) + 3) & ~3) - ((len(packed) + 3) & ~3),
        'adpcm_snr_db': round(10 * math.log10(signal / error), 2),
        'quality_measurement_limit': 'IMA SNR compares to resampled8192Hz PCM16; resampling bandwidth loss and final8-bit quantization are not included.',
    }
    header = '\n'.join([
        '/* Generated by tools/pack_menu_audio.py; title/main-menu music only. */',
        '#pragma once', '#include <stdint.h>',
        'extern const uint8_t asset_audio_music_menu_adpcm[];',
        '#define MENU_AUDIO_RATE 8192', '#define MENU_AUDIO_REPEAT 2',
        f'#define MENU_AUDIO_SAMPLES {len(samples)}',
        f'#define MENU_AUDIO_OUTPUT_SAMPLES {len(samples) * 2}',
        f'#define MENU_AUDIO_BYTES {len(packed)}', '',
    ])
    outputs = {
        ROOT / 'generated/audio_music_menu_adpcm.lz': packed,
        ROOT / 'generated/menu_audio.h': header.encode(),
        ROOT / 'generated/menu-audio-report.json': (json.dumps(metadata, indent=2) + '\n').encode(),
    }
    for path, data in outputs.items():
        if args.check:
            assert path.read_bytes() == data, str(path)
        else:
            path.write_bytes(data)
    print(json.dumps(metadata, indent=2))


if __name__ == '__main__':
    main()
