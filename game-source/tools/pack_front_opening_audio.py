#!/usr/bin/env python3
"""Pack the blue startup logo's audio as direct-DMA 8192 Hz signed PCM8.

The source contains both logos. Keep nominal seconds 0..11 for the blue logo;
the white Blizzard North segment is silent and has no stored audio body.
The .lz suffix is the asset bundle convention, not an LZ compression format.
"""
from array import array
from pathlib import Path
import argparse
import hashlib
import json
import math
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'source_assets/frontend/opening.smk'
SOURCE_SHA = 'e2c197ac9e17257ccc34ca79b931a10a20c90bec0fd7b587517da217174314b2'
RATE = 8192
SECONDS = 11
SAMPLES = RATE * SECONDS
GUARD = 4096


def sha(data):
    return hashlib.sha256(data).hexdigest()


def decode(rate, format_name):
    return subprocess.check_output([
        'ffmpeg', '-v', 'error', '-i', str(SOURCE), '-map', '0:a:0',
        '-vn', '-ac', '1', '-ar', str(rate), '-f', format_name, '-'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assert sha(SOURCE.read_bytes()) == SOURCE_SHA, 'Unexpected opening source'

    # Reconstruct the old direct PCM asset for a source-derived comparison.
    # It included all 16 seconds plus the same 4096-byte guard and alignment.
    legacy = decode(16384, 's8')
    legacy_asset = legacy + bytes((-len(legacy)) % 4 + GUARD)
    assert len(legacy_asset) == 266216
    assert not any(legacy[SECONDS * 16384:]), 'White-logo PCM must be silent'

    converted = decode(RATE, 's8')
    assert len(converted) >= SAMPLES
    body = converted[:SAMPLES]
    payload = body + bytes((-len(body)) % 4 + GUARD)
    assert len(payload) == 94208 and len(payload) % 4 == 0
    assert not any(body[-32:]), 'The blue-logo cut must end in silence'
    assert not any(payload[SAMPLES:]), 'DMA guard must be entirely zero'

    pcm16 = array('h', decode(RATE, 's16le')[:SAMPLES * 2])
    if sys.byteorder != 'little':
        pcm16.byteswap()
    pcm8 = array('b', body)
    signal = sum(int(v) ** 2 for v in pcm16)
    error = sum((int(a) - int(b) * 256) ** 2 for a, b in zip(pcm16, pcm8))
    last_nonzero = max(i for i, value in enumerate(body) if value)
    header = '\n'.join([
        '/* Generated by tools/pack_front_opening_audio.py. Direct PCM8 DMA. */',
        '#pragma once',
        '#define FRONT_OPENING_AUDIO_RATE 8192',
        '#define FRONT_OPENING_AUDIO_TIMER_RELOAD 0xf800',
        '#define FRONT_OPENING_AUDIO_SAMPLES 90112',
        '#define FRONT_OPENING_AUDIO_GUARD_BYTES 4096',
        '#define FRONT_OPENING_AUDIO_BYTES 94208',
        '',
    ])
    report = {
        'source': str(SOURCE.relative_to(ROOT)), 'source_sha256': SOURCE_SHA,
        'format': 'signed8 mono PCM; direct ROM DMA; no runtime decoder',
        'native_rate': 22050, 'previous_rate': 16384, 'output_rate': RATE,
        'blue_seconds': SECONDS, 'blue_samples': SAMPLES,
        'white_audio_body_bytes': 0, 'white_previously_silent': True,
        'guard_bytes': GUARD, 'asset_bytes': len(payload),
        'asset_sha256': sha(payload),
        'previous_asset_bytes': len(legacy_asset),
        'previous_asset_sha256': sha(legacy_asset),
        'raw_aligned_bytes_saved': len(legacy_asset) - len(payload),
        'blue_last_nonzero_sample': last_nonzero,
        'blue_trailing_silent_samples': SAMPLES - last_nonzero - 1,
        'pcm8_peak': max(abs(v) for v in pcm8),
        'pcm8_rms': round(math.sqrt(sum(int(v) ** 2 for v in pcm8) / len(pcm8)), 4),
        'pcm8_quantization_snr_db': round(10 * math.log10(signal / error), 2),
        'quality_measurement_limit': 'SNR measures 8-bit quantization against the resampled 8192 Hz PCM16. It does not measure bandwidth lost by resampling 22050 Hz to 8192 Hz.',
        'dma_guard': {
            'conservative_prefetch_bytes': 64,
            'prefetch_bound_reason': 'FIFO32 + output latch4 + one DMA burst16 is52 bytes; round up to64 for the guard bound.',
            'safe_late_samples_after_blue': GUARD - 64,
            'safe_late_seconds_after_blue': (GUARD - 64) / RATE,
            'required_runtime_action': 'Stop DMA1 and Timer1 at the nominal 11-second blue/white boundary. With conservative 64-byte prefetch, stopping no more than 4032 samples late keeps every DMA read inside the payload. The guard is a bound, not permission to continue playback throughout the white logo.',
        },
    }
    outputs = {
        ROOT / 'generated/front_audio.lz': payload,
        ROOT / 'generated/front_opening_audio.h': header.encode(),
        ROOT / 'generated/front-opening-audio-report.json': (json.dumps(report, indent=2) + '\n').encode(),
    }
    for path, data in outputs.items():
        if args.check:
            assert path.read_bytes() == data, 'Generated asset differs: ' + str(path)
        else:
            path.write_bytes(data)
    print(json.dumps(report, indent=2))
    print('PASS opening audio source, silent cut, exact duration, aligned payload and DMA guard' + ('; checked generated files' if args.check else ''))


if __name__ == '__main__':
    main()
