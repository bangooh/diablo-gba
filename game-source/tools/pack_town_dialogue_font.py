"""Expose the approved Exocet bitmap as a complete printable-ASCII prose font.

This preserves every existing glyph pixel, including punctuation and the
capital-style lowercase forms. Runtime expands one 8x8 glyph at a time to
HUD BG1 tiles0..95 at0x06008000; this packer adds no palette or RAM state.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'source_assets/exocet/exocet-8x8-1bpp.bin'
OUTPUT = ROOT / 'generated/town_dialogue_font.h'


def build(size=7):
    source = SOURCE.read_bytes()
    if size==5:
        small=(ROOT/'source_assets/exocet/exocet-5x5-1bpp.bin').read_bytes()
        assert len(small)==640
        source=b''.join(small[c*5:c*5+5]+bytes(3) for c in range(128))
    assert len(source) == 128 * 8
    glyphs = [source[code * 8:(code + 1) * 8] for code in range(32, 128)]
    assert glyphs[0] == bytes(8), 'space must be blank'
    assert all(glyph[7] == 0 and all(row & 1 == 0 for row in glyph) for glyph in glyphs)
    assert all(any(glyph) for glyph in glyphs[1:]), 'every nonspace ASCII glyph exists'
    assert len(set(glyphs[65 - 32:91 - 32])) == 26
    for code in range(ord('a'), ord('z') + 1):
        assert glyphs[code - 32] == glyphs[code - 32 - 32]
    assert glyphs[ord('0') - 32] != glyphs[ord('O') - 32]
    assert glyphs[ord('1') - 32] != glyphs[ord('I') - 32]
    assert glyphs[ord(',') - 32] != glyphs[ord('.') - 32]
    assert glyphs[ord("'") - 32] != glyphs[ord('"') - 32]
    digest = hashlib.sha256(source).hexdigest()
    lines = [
        '/* Generated by tools/pack_town_dialogue_font.py. Do not edit.',
        ' * Exact approved Exocet7x7 pixels; printable ASCII and visible DEL fallback.',
        ' * Source: source_assets/exocet/exocet-8x8-1bpp.bin',
        f' * Source SHA256: {digest}',
        ' * Index=ASCII-32. Eight rows, bit7=left; row7/bit0 are blank spacing.',
        ' * Lowercase uses the approved capital-style form; prose bytes stay intact.',
        ' * BG1 remains8bpp/charbase2: glyph tiles0..95 occupy8000..97FF.',
        ' * Hide BG0 while loaded. Before showing town again, invalidate terrain',
        ' * cache slots512..607 and rebuild their visible tiles via stream_town().',
        ' * Existing HUD tile96 and fonts97+ are outside this allocation. */',
        '#pragma once',
        '#include <stdint.h>',
        'enum { TOWN_DIALOGUE_FONT_FIRST=32, TOWN_DIALOGUE_FONT_LAST=127,',
        '       TOWN_DIALOGUE_FONT_GLYPHS=96, TOWN_DIALOGUE_FONT_ROWS=8,',
        f'       TOWN_DIALOGUE_FONT_INK_WIDTH={size}, TOWN_DIALOGUE_FONT_INK_HEIGHT={size},',
        '       TOWN_DIALOGUE_FONT_ADVANCE=8, TOWN_DIALOGUE_FONT_LINE_HEIGHT=8,',
        '       TOWN_DIALOGUE_FONT_FIRST_TILE=0, TOWN_DIALOGUE_FONT_VRAM_BYTES=6144 };',
        'static const uint8_t town_dialogue_font[96][8] __attribute__((aligned(4))) = {',
    ]
    for code, glyph in enumerate(glyphs, 32):
        lines.append(' {' + ','.join(f'0x{row:02x}' for row in glyph) + f'}}, /* ASCII{code} */')
    lines.append('};')
    return ('\n'.join(lines) + '\n').encode(), digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--size',type=int,choices=[5,7],default=7)
    args = parser.parse_args()
    output, digest = build(args.size)
    if args.check:
        assert OUTPUT.read_bytes() == output, f'{OUTPUT.name} is stale'
    else:
        OUTPUT.write_bytes(output)
    print(f'PASS:96 glyphs,768ROM bytes,6144VRAM bytes,0RAM bytes; source SHA256 {digest}')


if __name__ == '__main__':
    main()
