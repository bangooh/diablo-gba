"""Pack exact binary-light ellipse spans; radius10 is80x50 screen pixels.

The former four-band light_raster.h is historical and is not used or rewritten.
"""
import argparse
from math import isqrt
from pathlib import Path


def render():
    rows = []
    for radius in range(16):
        spans = []
        for y in range(76):
            remaining = 1600 * radius * radius - 64 * y * y
            spans.append(isqrt(remaining // 25) if remaining >= 0 else 255)
        rows.append('{' + ','.join(map(str, spans)) + '}')
    return ('/* Generated by pack_light_spans.py; radius10 is80x50. '
            '255 means no lit pixels on this row. */\n'
            'static const uint8_t light_spans[16][76]={\n'
            + ',\n'.join(rows) + '\n};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify without writing')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'generated/light_spans.h'
    expected = render()
    if args.check:
        if path.read_text() != expected:
            raise SystemExit('generated/light_spans.h is stale')
        print('PASS: binary80x50 light spans,1216 bytes')
    else:
        path.write_text(expected)
        print('Wrote generated/light_spans.h:1216 bytes')


if __name__ == '__main__':
    main()
