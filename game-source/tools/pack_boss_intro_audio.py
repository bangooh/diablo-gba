#!/usr/bin/env python3
"""Pack seven original first-encounter cues for the existing PCM effect mixer.

The voice occupies the independent item channel, leaving combat sounds active.
Lachdanan and Diablo are intentionally excluded by the approved source catalog.
"""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess
import wave
from audio_pcm import EFFECT_GUARD, guarded_pcm

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog = json.loads((ROOT / 'source_assets/boss_speech_stage53/boss-speech-catalog.json').read_text())
    voices = [row for row in catalog['voices'] if row['production']]
    assert [row['voice_id'] for row in voices] == list(range(7))
    header = ['/* Generated by tools/pack_boss_intro_audio.py; original first cues. */',
              '#pragma once', '#include <stdint.h>',
              '#define BOSS_INTRO_AUDIO_RATE 16384', '#define BOSS_INTRO_AUDIO_COUNT 7']
    entries, outputs = [], {}
    report = {'scope': 'Seven original first-encounter cues; Lachdanan and Diablo excluded',
              'codec': 'Signed8 mono PCM, full source duration, existing effect gain0.85',
              'rate': 16384, 'guard_bytes': EFFECT_GUARD,
              'runtime': 'Existing independent item/DMA2 voice; combat mixes concurrently; no decoder or new RAM',
              'clips': []}
    for row in voices:
        name = row['key'].lower()
        source = ROOT / 'source_assets/boss_intros' / row['mpq_path'].rsplit('\\', 1)[-1]
        with wave.open(str(source)) as native:
            native_samples, native_rate = native.getnframes(), native.getframerate()
        pcm = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(source),
                                       '-ac', '1', '-ar', '16384', '-af', 'volume=0.85',
                                       '-f', 's8', '-'])
        payload = guarded_pcm(pcm)
        symbol = 'asset_audio_boss_intro_' + name
        length = 'AUDIO_BOSS_INTRO_' + row['key'] + '_LENGTH'
        filename = 'audio_boss_intro_' + name + '.lz'
        outputs[ROOT / 'generated' / filename] = payload
        header += ['extern const uint8_t ' + symbol + '[];', '#define ' + length + ' ' + str(len(pcm))]
        entries.append('{' + symbol + ',' + length + '}')
        report['clips'].append({
            'voice_id': row['voice_id'], 'key': row['key'], 'name': row['name'],
            'mpq_path': row['mpq_path'], 'sfx': row['sfx'],
            'source': str(source.relative_to(ROOT)),
            'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
            'native_rate': native_rate, 'native_samples': native_samples,
            'native_seconds': native_samples / native_rate,
            'samples': len(pcm), 'seconds': len(pcm) / 16384,
            'bytes': len(payload), 'guard_bytes': len(payload) - len(pcm),
            'symbol': symbol, 'filename': filename,
            'pcm_sha256': hashlib.sha256(pcm).hexdigest(),
            'asset_sha256': hashlib.sha256(payload).hexdigest(),
        })
    header += ['#define BOSS_INTRO_AUDIO_SAMPLES ' + ','.join(entries), '']
    report['total_seconds'] = sum(clip['seconds'] for clip in report['clips'])
    report['total_asset_bytes'] = sum(clip['bytes'] for clip in report['clips'])
    report['metadata_rom_bytes'] = 8 * len(voices)
    report['dma_guard_bound_samples'] = 275 + 32
    assert EFFECT_GUARD > report['dma_guard_bound_samples']
    outputs[ROOT / 'generated/boss_intro_audio.h'] = '\n'.join(header).encode()
    outputs[ROOT / 'generated/boss-intro-audio-report.json'] = (json.dumps(report, indent=2) + '\n').encode()
    for path, data in outputs.items():
        if args.check:
            assert path.read_bytes() == data, str(path)
        else:
            path.write_bytes(data)
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
