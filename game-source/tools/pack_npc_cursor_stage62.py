#!/usr/bin/env python3
"""Pack Diablo's original paired store selector into the existing town palette.

Normal builds use the checked-in CEL/PAL; --extract requires the original MPQ
and the project's mpyq/dclimplode dependencies. No generated or invented art.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'source_assets/npc_ui_stage62'
FILES = {'PentSpn2.CEL': r'Data\PentSpn2.CEL',
         'Town.PAL': r'Levels\TownData\Town.PAL'}
WIDTH, HEIGHT, FRAMES = 8, 8, 8
NPCS = [('Smith', 'Griswold the Blacksmith'),
        ('BarOwner', 'Ogden the Tavern owner'),
        ('TownDead', 'Wounded Townsman'), ('Witch', 'Adria the Witch'),
        ('Barmaid', 'Gillian the Barmaid'), ('Boy', 'Wirt the Peg-legged boy'),
        ('Healer', 'Pepin the Healer'), ('Teller', 'Cain the Elder'),
        ('Drunk', 'Farnham the Drunk')]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def decode_cel(data):
    """Unheaded store CEL: signed transparent/literal runs, bottom-up rows."""
    count = struct.unpack_from('<I', data)[0]
    assert count == FRAMES
    offsets = struct.unpack_from('<9I', data, 4)
    assert offsets[0] == 40 and offsets[-1] == len(data)
    result = []
    for a, b in zip(offsets, offsets[1:]):
        assert a < b
        p, pixels = a, bytearray()
        while p < b:
            run = data[p]
            p += 1
            if run >= 128:
                pixels.extend(bytes(256 - run))
            else:
                assert run and p + run <= b
                pixels.extend(data[p:p + run])
                p += run
        assert p == b and len(pixels) == 12 * 12
        result.append(Image.frombytes('P', (12, 12), bytes(pixels)).transpose(
            Image.Transpose.FLIP_TOP_BOTTOM))
    return result


def build():
    raw = (SOURCE / 'PentSpn2.CEL').read_bytes()
    native_pal = (SOURCE / 'Town.PAL').read_bytes()
    town_raw = (ROOT / 'generated/town_palette.bin').read_bytes()
    assert len(native_pal) == 768 and len(town_raw) == 512
    town = struct.unpack('<256H', town_raw)
    target = [tuple(((c >> s) & 31) * 255 // 31 for s in (0, 5, 10)) for c in town]
    source = [tuple(native_pal[i:i + 3]) for i in range(0, 768, 3)]
    stores_path = ROOT / 'source_assets/town_dialogue_stage53/stores.cpp'
    towners_path = ROOT / 'source_assets/town_dialogue_stage53/towners.cpp'
    stores, towners = stores_path.read_text(), towners_path.read_text()
    names = []
    for npc, (function, expected_name) in enumerate(NPCS):
        section = towners.split('void Init' + function + '()', 1)[1].split('\n}', 1)[0]
        name = re.search(r'strcpy\(towner\[numtowners\]._tName, "([^"]+)"\)', section)[1]
        assert name == expected_name
        names.append({'port_npc_id': npc, 'name': name, 'source_function': 'Init' + function})
    assert stores.count('pSPentSpn2Cels, InStoreFlag, 12)') == 2
    assert 'InStoreFlag = (InStoreFlag & 7) + 1;' in stores
    assert re.search(r'"Would you like to:", COL_GOLD, FALSE', stores)
    assert re.search(r'"Gossip", COL_BLUE, TRUE', stores)
    assert re.search(r'questlist\[i\]._qlstr, COL_WHITE, TRUE', stores)
    assert re.search(r'"Back", COL_WHITE, TRUE', stores)
    native = decode_cel(raw)
    used = sorted(set(b''.join(im.tobytes() for im in native)) - {0})
    mapping = {0: 0}
    for i in used:
        # Preserve native indices on equal distances, retaining the source's
        # stable red ramp where more than one index has the same RGB555 color.
        mapping[i] = min(range(1, 256), key=lambda j: (
            sum((target[j][k] - source[i][k]) ** 2 for k in range(3)), j != i, j))
    lut = bytes(mapping.get(i, 0) for i in range(256))
    frames, sampled = [], []
    for im in native:
        small = im.resize((WIDTH, HEIGHT), Image.Resampling.NEAREST)
        # Independently verify every nearest-neighbor source coordinate.
        expected = bytes(im.getpixel(((2*x+1)*12//16, (2*y+1)*12//16))
                         for y in range(8) for x in range(8))
        assert small.tobytes() == expected
        packed = small.tobytes().translate(lut)
        assert all(bool(a) == bool(b) for a, b in zip(small.tobytes(), packed))
        sampled.append(small)
        frames.append(packed)
    assert len(set(frames)) == FRAMES and len(set(frames[0]) - {0}) >= 3
    header = ['/* Generated by pack_npc_cursor_stage62.py; original Data/PentSpn2.CEL.',
              ' * 8x8 nearest sample of each 12x12 frame; direct town BG indices.',
              ' * Index0 is transparent. Draw both sides without mirroring.',
              ' * Existing town palette and global gamma apply; no palette writes. */',
              '#pragma once', '#include <stdint.h>',
              '#define NPC_MENU_CURSOR_WIDTH 8', '#define NPC_MENU_CURSOR_HEIGHT 8',
              '#define NPC_MENU_CURSOR_FRAMES 8', '#define NPC_MENU_CURSOR_FACE_FRAME 0',
              'static const uint8_t npc_menu_cursor[8][64] = {']
    for n, frame in enumerate(frames):
        header.append(' /* Native frame %d. */ {' % (n + 1))
        header.extend('  ' + ','.join(str(v) for v in frame[y*8:(y+1)*8]) + ','
                      for y in range(8))
        header.append(' },')
    header.extend(['};', ''])
    report = {
        'status': 'PASS', 'asset': FILES['PentSpn2.CEL'],
        'native': {'size': [12, 12], 'frames': 8, 'selected_frames_1based': list(range(1, 9))},
        'packed': {'size': [8, 8], 'frames': 8, 'rom_bytes': 512, 'persistent_ram_bytes': 0,
                   'new_palette_entries': 0, 'new_obj_entries': 0,
                   'format': 'row-major 8-bit existing town BG palette indices; 0 transparent',
                   'sha256': sha(b''.join(frames))},
        'source_files': [{'path': str((SOURCE / name).relative_to(ROOT)),
                          'mpq_path': path, 'bytes': len((SOURCE / name).read_bytes()),
                          'sha256': sha((SOURCE / name).read_bytes())}
                         for name, path in FILES.items()],
        'town_palette_sha256': sha(town_raw),
        'palette_mapping': [{'source_index': i, 'source_rgb888': source[i],
                             'town_index': mapping[i], 'town_rgb555': town[mapping[i]],
                             'town_rgb888': target[mapping[i]]} for i in used],
        'original_selector': {
            'source': 'source_assets/town_dialogue_stage53/stores.cpp',
            'load': 'InitStores: Data\\PentSpn2.CEL',
            'draw': 'PrintSString: same InStoreFlag frame, width12, both sides; no mirror',
            'animation': 'DrawSText: InStoreFlag=(InStoreFlag&7)+1',
            'runtime_policy': 'Representative native frame1; full8-frame data preserved'},
        'source_audit': {
            'commit': '9f01757243412bb154d02d9af65c804159e6e0ea',
            'files': [{'path': str(path.relative_to(ROOT)), 'sha256': sha(path.read_bytes())}
                      for path in (stores_path, towners_path)],
            'full_names': names,
            'option_colors': {'full_name_header': 'COL_GOLD', 'Would you like to:': 'COL_GOLD',
                              'Talk to <first name>': 'COL_BLUE', 'Gossip': 'COL_BLUE',
                              'quest_topic': 'COL_WHITE', 'service': 'COL_WHITE',
                              'Say goodbye': 'COL_WHITE', 'Back': 'COL_WHITE'},
            'native_font_brightest_rgb888': {'white': source[240], 'blue': source[178],
                                            'gold': source[194], 'red': source[224]},
            'adaptations': ['Header uses full towners.cpp name consistently; native store headings vary.',
                            'Would you like to: also appears in Wirt/topics for consistent requested UI.',
                            'Goodbye wording normalized as Say goodbye; native shop exits vary.',
                            'Static first original pentagram frame avoids repeated canvas rendering.']},
        'checks': {'all_cel_runs_bounded': True, 'all_native_frames_12x12': True,
                   'nearest_source_coordinates_exact': True,
                   'transparency_preserved': True, 'all8_frames_distinct': True,
                   'source_face_shading_preserved': True}}
    # Native and GBA samples are displayed without interpolation for inspection.
    sheet = Image.new('RGB', (8*104, 184), (20, 20, 20))
    draw = ImageDraw.Draw(sheet)
    for n, im in enumerate(native):
        im.putpalette(native_pal)
        sheet.paste(im.convert('RGB').resize((72, 72), Image.Resampling.NEAREST), (n*104+8, 20))
        packed = Image.frombytes('P', (8, 8), frames[n])
        packed.putpalette(bytes(v for color in target for v in color))
        sheet.paste(packed.convert('RGB').resize((48, 48), Image.Resampling.NEAREST), (n*104+20, 112))
        draw.text((n*104+8, 3), 'Frame ' + str(n+1), fill='white')
    draw.text((8, 168), 'Top: original 12x12. Bottom: GBA 8x8, unchanged town palette.', fill='white')
    return {'npc_menu_cursor.h': '\n'.join(header).encode(),
            'npc_menu_cursor-report.json': (json.dumps(report, indent=2)+'\n').encode()}, sheet, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--extract', type=Path, help='Original DIABDAT.MPQ')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.extract:
        assert not args.check
        import mpyq
        from extract_assets import read_mpq
        archive = mpyq.MPQArchive(str(args.extract), listfile=False)
        SOURCE.mkdir(exist_ok=True)
        for name, path in FILES.items():
            (SOURCE / name).write_bytes(read_mpq(archive, path))
    outputs, sheet, report = build()
    for filename, data in outputs.items():
        path = ROOT / 'generated' / filename
        if args.check:
            assert path.read_bytes() == data, path
        else:
            path.write_bytes(data)
    if not args.check:
        sheet.save(ROOT / 'generated/npc_menu_cursor-preview.png')
    print(json.dumps({'status': 'PASS', 'rom_bytes': report['packed']['rom_bytes'],
                      'source': report['asset'], 'check_only': args.check}))


if __name__ == '__main__':
    main()
